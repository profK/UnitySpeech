# Binary protocol for streaming TTS responses from worker to client.
#
# All records are length-prefixed and little-endian.
# The HTTP response body is a concatenation of records; the client must
# tolerate arbitrary read boundaries.
#
# ┌───────────┬──────────┬──────────┬──────────────────────────┐
# │  Type (1) │  Length  │ Payload  │  Padding (to 8-byte)     │
# │  (uint8)  │ (uint32) │  (bytes) │                         │
# └───────────┴──────────┴──────────┴──────────────────────────┘
#
# The wire length includes payload only (no type, length, or padding bytes).

from __future__ import annotations

import struct
import time
from dataclasses import dataclass, field
from enum import IntEnum
from typing import Generator, List, Optional, Tuple

PROTOCOL_VERSION = 1  # uint8 version marker at start of every response

# Record types (single byte)
RECORD_START  = 0x01
RECORD_PCM    = 0x02
RECORD_END    = 0x03
RECORD_ERROR  = 0x04

# PCM format: mono, 16-bit signed little-endian, 24 kHz
SAMPLE_RATE = 24000
SAMPLES_PER_FRAME = 480  # 20 ms per PCM record

# Header: 1 (type) + 4 (length) = 5 bytes
_HEADER_FMT = "<B I"
_HEADER_SIZE = struct.calcsize(_HEADER_FMT)  # 5

# End record payload: total_samples (uint32) + timing fields
_END_FMT = "<I d d d"  # total_samples, wall_ms, inference_ms, silence_ms
_END_PAYLOAD_SIZE = struct.calcsize(_END_FMT)

# Error record payload: code (int32) + message length (uint16) + message UTF-8
_ERROR_HEADER_FMT = "<i H"
_ERROR_HEADER_SIZE = struct.calcsize(_ERROR_HEADER_FMT)

# Alignment: pad each record to 8-byte boundary
_ALIGNMENT = 8


class TerminalReason(IntEnum):
    """Canonical failure reasons reported to the client."""
    OK = 0
    UnknownVoice = 1
    QueueOverload = 2
    WorkerUnavailable = 3
    Timeout = 4
    ProtocolError = 5
    PlaybackFailure = 6
    InferenceError = 7


@dataclass
class SpeechTiming:
    """Worker-measured timing deltas (monotonic ms)."""
    wall_ms: float = 0.0          # Total wall time
    inference_ms: float = 0.0     # Active model time
    voice_prep_ms: float = 0.0    # Voice prompt preparation
    first_pcm_ms: float = 0.0     # First PCM record produced
    silence_head_ms: float = 0.0  # Leading silence generated by model


def _pad(payload: bytes) -> bytes:
    """Pad payload to 8-byte alignment."""
    rem = len(payload) % _ALIGNMENT
    if rem:
        return payload + b"\x00" * (_ALIGNMENT - rem)
    return payload


def _encode_header(record_type: int, length: int) -> bytes:
    return struct.pack(_HEADER_FMT, record_type, length)


# ── Start record ────────────────────────────────────────────────────
# Payload: version (uint8) + voice_id (len16 + UTF-8) + language (len16 + UTF-8)
#          + duration_seconds (float64) + sample_rate (uint32)

def encode_start(voice_id: str, language: str,
                 estimated_duration_s: float) -> bytes:
    vid_bytes = voice_id.encode("utf-8")
    lang_bytes = language.encode("utf-8")
    payload = (
        struct.pack("B", PROTOCOL_VERSION) +
        struct.pack("<H", len(vid_bytes)) + vid_bytes +
        struct.pack("<H", len(lang_bytes)) + lang_bytes +
        struct.pack("<d I", estimated_duration_s, SAMPLE_RATE)
    )
    padded = _pad(payload)
    return _encode_header(RECORD_START, len(padded)) + padded


def decode_start(payload: bytes):
    off = 0
    version = struct.unpack_from("B", payload, off)[0]; off += 1
    vid_len = struct.unpack_from("<H", payload, off)[0]; off += 2
    voice_id = payload[off:off + vid_len].decode("utf-8"); off += vid_len
    lang_len = struct.unpack_from("<H", payload, off)[0]; off += 2
    language = payload[off:off + lang_len].decode("utf-8"); off += lang_len
    duration_s, sr = struct.unpack_from("<d I", payload, off)
    return version, voice_id, language, duration_s, sr


# ── PCM record ──────────────────────────────────────────────────────
# Payload: offset (uint64, contiguous sample index) + raw PCM bytes

_PCM_HDR_FMT = "<Q I"  # sample_offset + pcm_length
_PCM_HDR_SIZE = struct.calcsize(_PCM_HDR_FMT)  # 12


def encode_pcm(sample_offset: int, pcm_bytes: bytes) -> bytes:
    payload = struct.pack(_PCM_HDR_FMT, sample_offset, len(pcm_bytes)) + pcm_bytes
    padded = _pad(payload)
    return _encode_header(RECORD_PCM, len(padded)) + padded


def decode_pcm(payload: bytes) -> Tuple[int, bytes]:
    offset, pcm_len = struct.unpack_from(_PCM_HDR_FMT, payload, 0)
    pcm_start = _PCM_HDR_SIZE
    return offset, payload[pcm_start:pcm_start + pcm_len]


# ── End record ──────────────────────────────────────────────────────

def encode_end(total_samples: int, timing: SpeechTiming) -> bytes:
    payload = struct.pack(_END_FMT, total_samples,
                          timing.wall_ms, timing.inference_ms,
                          timing.silence_head_ms)
    padded = _pad(payload)
    return _encode_header(RECORD_END, len(padded)) + padded


def decode_end(payload: bytes) -> Tuple[int, SpeechTiming]:
    total, wall, inf, silence = struct.unpack_from(_END_FMT, payload, 0)
    return total, SpeechTiming(
        wall_ms=wall, inference_ms=inf, silence_head_ms=silence
    )


# ── Error record ────────────────────────────────────────────────────

def encode_error(reason: TerminalReason, message: str = "") -> bytes:
    msg_bytes = message.encode("utf-8")
    payload = struct.pack(_ERROR_HEADER_FMT, reason.value, len(msg_bytes)) + msg_bytes
    padded = _pad(payload)
    return _encode_header(RECORD_ERROR, len(padded)) + padded


def decode_error(payload: bytes):
    code, msg_len = struct.unpack_from(_ERROR_HEADER_FMT, payload, 0)
    msg = payload[_ERROR_HEADER_SIZE:_ERROR_HEADER_SIZE + msg_len].decode("utf-8")
    return TerminalReason(code), msg


# ── Framed reader ───────────────────────────────────────────────────
# Tolerates arbitrary read boundaries (partial records, multiple records per read).

class RecordReader:
    """Pulls typed records from an arbitrary byte stream."""

    def __init__(self) -> None:
        self._buf = bytearray()

    def feed(self, data: bytes) -> List[Tuple[int, bytes]]:
        """Ingest raw bytes and return any complete records."""
        self._buf.extend(data)
        records = []
        while True:
            if len(self._buf) < _HEADER_SIZE:
                break
            rtype, length = struct.unpack_from(_HEADER_FMT, self._buf, 0)
            total_needed = _HEADER_SIZE + length
            if len(self._buf) < total_needed:
                break  # wait for more data
            payload = bytes(self._buf[_HEADER_SIZE:total_needed])
            # Validate record size before any allocation
            if length > 16 * 1024 * 1024:  # 16 MB guard
                raise ValueError(f"Record length {length} exceeds 16 MB guard")
            records.append((rtype, payload))
            self._buf = self._buf[total_needed:]
        return records

    def remaining(self) -> bytes:
        return bytes(self._buf)
